import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, writeFileSync, rmSync, readdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { compatibility, generate, root, sourceFiles, sourceIdentity } from "../native/qt/scripts/generate-config.mjs";
import { packageNative } from "../native/qt/scripts/package.mjs";
import { loadQtNativePackage } from "../dist/qt-native-package.js";
import { loadProductProfile } from "../dist/product-profiles.js";

const temporary = mkdtempSync(join(tmpdir(), "sse-native-build-"));
const hash = bytes => createHash("sha256").update(bytes).digest("hex");
// Minimal PE-shaped buffers exercise packaging validation only; no generated byte is executed.
function pe(name, identity) {
  const bytes = Buffer.alloc(512); bytes.write("MZ"); bytes.writeUInt32LE(128, 0x3c);
  bytes.writeUInt32LE(0x00004550, 128); bytes.writeUInt16LE(0x8664, 132); bytes.writeUInt16LE(0x20b, 152);
  bytes.writeUInt16LE(name.endsWith(".dll") ? 0x2000 : 2, 150);
  bytes.write("SSE_NATIVE_BRIDGE_V2:" + identity + "\0", 256);
  const path = join(temporary, name); writeFileSync(path, bytes); return path;
}
try {
  const upstream = JSON.parse(readFileSync(join(root, "third_party/nlohmann/UPSTREAM.json"), "utf8"));
  assert.equal(upstream.version, "3.11.2");
  assert.equal(hash(readFileSync(join(root, "third_party/nlohmann/json.hpp"))), upstream.headerSha256);
  assert.equal(hash(readFileSync(join(root, "third_party/nlohmann/LICENSE.MIT"))), upstream.licenseSha256);
  for (const name of readdirSync(root).filter(name => /\.(?:h|cpp)$/u.test(name))) {
    assert(sourceFiles.includes(name), "Native startup/read source missing from the build identity: " + name);
  }
  assert.equal(new Set(sourceFiles).size, sourceFiles.length);
  const generated = join(temporary, "generated"), identity = generate(generated);
  assert.match(identity, /^[a-f0-9]{64}$/u); assert.equal(identity, sourceIdentity());
  assert.deepEqual(compatibility().profile, { id: "2025", taxYear: 2025, engineFileMajor: 31, verifiedBuild: "31.0.2.0", qtVersion: "6.9.2" });
  const header = join(generated, "bridge-identity.h"), loader = pe("bridge-load.exe", identity), bridge = pe("sse-qt-read.dll", identity);
  const packaged = packageNative(loader, bridge, header, temporary);
  const verified = loadQtNativePackage(packaged.qtNativeRuntime, loadProductProfile("2025"));
  assert.equal(verified.manifest.buildIdentity, "SSE_NATIVE_BRIDGE_V2:" + identity);
  assert.equal(hash(readFileSync(verified.loaderPath)), verified.manifest.loader.sha256);
  assert.equal(hash(readFileSync(join(verified.directory, "LICENSE.nlohmann-json"))), hash(readFileSync(join(root, "third_party/nlohmann/LICENSE.MIT"))));
  assert.deepEqual(packageNative(loader, bridge, header, temporary), packaged, "Identical builds must reuse exactly the same verified package.");
  assert.deepEqual(JSON.parse(readFileSync(join(temporary, "native-package.json"), "utf8")), packaged);
  const savedBridge = readFileSync(verified.bridgePath);
  writeFileSync(verified.bridgePath, Buffer.concat([savedBridge, Buffer.from("tamper")]));
  assert.throws(() => packageNative(loader, bridge, header, temporary));
  writeFileSync(verified.bridgePath, savedBridge);
  writeFileSync(join(verified.directory, "LICENSE.nlohmann-json"), "missing license text");
  assert.throws(() => packageNative(loader, bridge, header, temporary), /notice differs/u);
  pe("bridge-load.exe", "0".repeat(64));
  assert.throws(() => packageNative(loader, bridge, header, temporary), /loader.*source identity/u);
  pe("bridge-load.exe", identity);
  const invalidPe = readFileSync(bridge); invalidPe.writeUInt16LE(0x14c, 132); writeFileSync(bridge, invalidPe);
  assert.throws(() => packageNative(loader, bridge, header, temporary));
  pe("sse-qt-read.dll", identity);
  writeFileSync(header, '#define SSE_BRIDGE_SOURCE_DIGEST "' + "0".repeat(64) + '"\n');
  assert.throws(() => packageNative(loader, bridge, header, temporary), /stale/u);
} finally {
  const resolved = resolve(temporary);
  assert(resolved.startsWith(resolve(tmpdir()) + "/") || resolved.startsWith(resolve(tmpdir()) + "\\"));
  rmSync(resolved, { recursive: true, force: true });
}
console.log("Native build contract: source identity, product binding, PE architecture, content-addressed package and bundled notices verified.");
